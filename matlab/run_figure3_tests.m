function run_figure3_tests()
%RUN_FIGURE3_TESTS Validate the corrected angle-dependent process zones.

material = struct('E1', 0.5, 'E2', 1.0, 'nu1', 0.3, 'nu2', 0.3);
cases = figure3_case_definitions();
assert(isequal([cases.material_index], [2, 1, 2, 1]), ...
    'Unexpected Figure-3 material order.');
assert(isequal([cases.sigma_prime], [0.5, -0.5, -0.5, 0.5]), ...
    'Unexpected Figure-3 load order.');

alphaDeg = (1:179)';
rootData = sweep_characteristic_roots(alphaDeg, material);
admissibility = calculate_figure4_admissibility( ...
    rootData.alpha_deg, rootData.lambda0, material);
caseMasks = [ ...
    admissibility.C_positive.material2, ...
    admissibility.C_negative.material1, ...
    admissibility.C_negative.material2, ...
    admissibility.C_positive.material1];
assert(isequal(find(caseMasks(:, 1))', 1:12), ...
    'Unexpected positive-load material-2 angle range.');
assert(isequal(find(caseMasks(:, 2))', 13:89), ...
    'Unexpected negative-load material-1 angle range.');
assert(isequal(find(caseMasks(:, 3))', 91:107), ...
    'Unexpected negative-load material-2 angle range.');
assert(isequal(find(caseMasks(:, 4))', 108:179), ...
    'Unexpected positive-load material-1 angle range.');
assert_close(admissibility.alpha1_deg, 12.9141, ...
    2e-4, 'alpha1 transition');
assert_close(admissibility.alpha2_deg, 107.0842, ...
    2e-4, 'alpha2 transition');

% Independent corrected Mathcad table supplied by the author. These values
% are a regression test of the author's numerical procedure, which used
% contour truncation 40 and G2(1e-5) instead of the analytic G2(0).
authorLambda = [ ...
    -0.962426216192013; -0.946421650399447; ...
    -0.933829942453543; -0.922946288015899; ...
    -0.913114675229351; -0.904000455099151; ...
    -0.895405679592306; -0.887201787328731; ...
    -0.879299664085376; -0.871634481631286; ...
    -0.864157276874679; -0.856829937650789];
authorD2 = [ ...
    0.000335848036383; 0.001314318095350; ...
    0.002939342835206; 0.005214427829153; ...
    0.008131366777493; 0.011670272948529; ...
    0.015801080267111; 0.020485155323992; ...
    0.025676831885607; 0.031324808640886; ...
    0.037373379486370; 0.043763489645494];
authorDelta2 = [ ...
    0.000277858125562; 0.001473394658848; ...
    0.003916037566077; 0.007832958013064; ...
    0.013385843604378; 0.020681078339157; ...
    0.029775583145880; 0.040681273022382; ...
    0.053369064186472; 0.067772709984504; ...
    0.083792510427657; 0.101298881684953];
authorJ2 = [ ...
    0.000234391474616; 0.000923208676185; ...
    0.002069888614866; 0.003673123357498; ...
    0.005722464738415; 0.008198438103713; ...
    0.011073535445677; 0.014313534991207; ...
    0.017878856416312; 0.021725819933612; ...
    0.025807761883582; 0.030075999768689];

factor40 = struct('truncation', 40, ...
    'relative_tolerance', 1e-10, 'absolute_tolerance', 1e-12);
options40 = struct('factor_options', factor40);
authorProcedureResults = cell(12, 1);
convergedSmallAngleResults = cell(12, 1);
maximumAuthorConvergedDifference = 0;
for alpha = 1:12
    authorResult = calculate_process_zone_parameters( ...
        deg2rad(alpha), material, 2, 0.5, options40);
    authorProcedureResults{alpha} = authorResult;
    assert_close(authorResult.lambda, authorLambda(alpha), 2e-9, ...
        sprintf('lambda at alpha=%d degrees', alpha));
    assert_close_scaled(authorResult.d_over_l, authorD2(alpha), ...
        1e-4, 5e-9, sprintf('author d2/l at alpha=%d degrees', alpha));
    assert_close_scaled(authorResult.delta_prime, authorDelta2(alpha), ...
        1e-4, 5e-9, ...
        sprintf('author delta2Prime at alpha=%d degrees', alpha));
    assert_close_scaled(authorResult.J_prime, authorJ2(alpha), ...
        1e-4, 5e-9, sprintf('author J2Prime at alpha=%d degrees', alpha));

    factorOptions = figure3_factor_options(deg2rad(alpha));
    convergedResult = calculate_process_zone_parameters( ...
        deg2rad(alpha), material, 2, 0.5, ...
        struct('factor_options', factorOptions));
    convergedSmallAngleResults{alpha} = convergedResult;
    relativeDifferences = abs([ ...
        convergedResult.d_over_l ./ authorD2(alpha) - 1, ...
        convergedResult.delta_prime ./ authorDelta2(alpha) - 1, ...
        convergedResult.J_prime ./ authorJ2(alpha) - 1]);
    maximumAuthorConvergedDifference = max( ...
        maximumAuthorConvergedDifference, max(relativeDifferences));
end

% The independently established converged one-degree endpoint distinguishes
% the scientific sweep from the author's fixed-T=40 reproduction.
alphaOne = convergedSmallAngleResults{1};
assert_close(alphaOne.d_over_l, 0.000334567324703, 5e-13, ...
    'converged d2/l at alpha=1 degree');
assert_close(alphaOne.delta_prime, 0.000276833276375, 5e-13, ...
    'converged delta2Prime at alpha=1 degree');
assert_close(alphaOne.J_prime, 0.000235061074026, 5e-13, ...
    'converged J2Prime at alpha=1 degree');

% The converged Figure-3 sweep must remain consistent with the four
% independently checked Figure-2 endpoints at plot-relevant angles.
checkpointAngles = [10, 45, 105, 135];
checkpointMaterials = [2, 1, 2, 1];
checkpointSigma = [0.5, -0.5, -0.5, 0.5];
checkpointValues = [ ...
    0.031324806384, 0.067772705874, 0.021725821310; ...
    0.147434361718, 0.145442265271, 0.037164616543; ...
    0.037035709254, 0.013442776906, 0.003922572967; ...
    0.051010519435, 0.057865884298, 0.013307413787];
for k = 1:numel(checkpointAngles)
    alpha = checkpointAngles(k);
    if alpha <= 12
        result = convergedSmallAngleResults{alpha};
    else
        factorOptions = figure3_factor_options(deg2rad(alpha));
        result = calculate_process_zone_parameters( ...
            deg2rad(alpha), material, checkpointMaterials(k), ...
            checkpointSigma(k), struct('factor_options', factorOptions));
    end
    assert_close(result.d_over_l, checkpointValues(k, 1), 3e-6, ...
        sprintf('Figure-3 d/l checkpoint at %d degrees', alpha));
    assert_close(result.delta_prime, checkpointValues(k, 2), 3e-6, ...
        sprintf('Figure-3 deltaPrime checkpoint at %d degrees', alpha));
    assert_close(result.J_prime, checkpointValues(k, 3), 2e-6, ...
        sprintf('Figure-3 JPrime checkpoint at %d degrees', alpha));
end

% Increase the angle-adaptive contour exponent from 24 to 30 at the outer
% ends and on both sides of every admissibility or degeneracy boundary.
convergenceAngles = [1, 12, 13, 89, 91, 107, 108, 179];
maximumFactorDifference = 0;
maximumTerminalDeviation = 0;
for alpha = convergenceAngles
    sourceRow = find(alphaDeg == alpha);
    selectedCase = find(caseMasks(sourceRow, :));
    currentCase = cases(selectedCase);
    factorOptions = figure3_factor_options(deg2rad(alpha));
    extendedFactorOptions = figure3_factor_options(deg2rad(alpha), 1.25);
    result = calculate_process_zone_parameters( ...
        deg2rad(alpha), material, currentCase.material_index, ...
        currentCase.sigma_prime, struct('factor_options', factorOptions));
    extendedResult = calculate_process_zone_parameters( ...
        deg2rad(alpha), material, currentCase.material_index, ...
        currentCase.sigma_prime, ...
        struct('factor_options', extendedFactorOptions));
    factorDifference = max(abs( ...
        factor_vector(result) - factor_vector(extendedResult)));
    maximumFactorDifference = max(maximumFactorDifference, factorDifference);
    baseDiagnostics = ...
        result.asymptotic_coefficients.factor_diagnostics;
    terminalDeviation = max([ ...
        baseDiagnostics.terminal_log_deviation, ...
        result.factor_diagnostics.terminal_log_deviation]);
    maximumTerminalDeviation = max( ...
        maximumTerminalDeviation, terminalDeviation);
    assert(factorDifference < 2e-8, sprintf([ ...
        'Plus factors at alpha=%d degrees are not converged between ', ...
        'the baseline and extended adaptive contours (difference %.3g).'], ...
        alpha, factorDifference));
end
assert(maximumTerminalDeviation < 5e-6, sprintf([ ...
    'Figure-3 terminal kernel deviation %.3g exceeds the limit.'], ...
    maximumTerminalDeviation));

fprintf(['Figure-3 transitions: alpha1=%.4f deg, ', ...
    'alpha2=%.4f deg.\n'], admissibility.alpha1_deg, ...
    admissibility.alpha2_deg);
fprintf(['Maximum author-T=40 versus converged relative difference: ', ...
    '%.3g.\n'], maximumAuthorConvergedDifference);
fprintf(['Maximum adaptive-versus-extended plus-factor difference: ', ...
    '%.3g.\n'], maximumFactorDifference);
fprintf('Maximum terminal kernel log-deviation: %.3g.\n', ...
    maximumTerminalDeviation);
fprintf(['All Figure-3 tests passed: the author table was reproduced ', ...
    'with T=40 and the scientific sweep was independently converged.\n']);
end

function values = factor_vector(result)
values = [ ...
    result.asymptotic_coefficients.base_Gplus_lambda, ...
    result.asymptotic_coefficients.base_Gplus_lambda0, ...
    result.Gi_plus_lambda, result.Gi_plus_minus1];
end

function assert_close(actual, expected, tolerance, label)
if any(~isfinite(actual(:))) || any(abs(actual(:) - expected) > tolerance)
    error('characteristic_roots:RegressionFailure', ...
        '%s: expected %.15g, obtained %.15g.', label, expected, actual);
end
end

function assert_close_scaled(actual, expected, relativeTolerance, ...
        absoluteTolerance, label)
tolerance = absoluteTolerance + relativeTolerance .* abs(expected);
assert_close(actual, expected, tolerance, label);
end
